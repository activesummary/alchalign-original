// (Optional) Inline link color so Gmail mobile doesn’t force bright blue
function inlineBrandLinks(html, color, underlineHex) {
  if (!html) return html;
  // add style to <a> that don't already have one
  html = html.replace(/<a\b(?![^>]*\bstyle=)[^>]*?>/gi,
    `<a style="color:${color}; text-decoration:none; border-bottom:1px solid ${underlineHex};">`
  );
  // and lightly adjust any existing inline styles to inherit brand color
  html = html.replace(/<a\b([^>]*\bstyle=")([^"]*)"/gi,
    (_m, pre, s) => `<a ${pre}${s}${s.trim().endsWith(';')?'':';'} color:${color}; text-decoration:none; border-bottom:1px solid ${underlineHex};"`
  );
  return html;
}

