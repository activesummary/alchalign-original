function paraHTML(text=""){
  // paragraphize: double newline => new paragraph, single => <br>
  return escapeHtml(text).split(/\n{2,}/).map(p=>`<p>${p.replace(/\n/g,"<br>")}</p>`).join("");
}

function sectionBlock(title, body, isAttn=false){
  if (!body) return "";
  const cls = isAttn ? "fathom-section attunement" : "fathom-section";
  return `
    <div class="${cls}">
      <h3 class="fathom-h3">${escapeHtml(title)}</h3>
      <div class="fathom-body">${paraHTML(body)}</div>
    </div>
  `;
}

