function buildPremiumEmailHTML({ product="fathom", card={}, reportUrl }) {
  const preheader = "Your reflective insight is ready."; // no dates/symptoms
  const theme = THEMES[product] || THEMES.fathom;

  const blocks = [
    ["On the Surface",      card.onTheSurface],
    ["Consider This",       card.considerThis],
    ["The Undercurrent",    card.theUndercurrent],
    ["What’s Emerging",     card.whatsEmerging],
    ["What's Running Your Life",        card.whatsRunningYourLife],
    ["The Exchange",        card.theExchange],
    ["Hidden Intelligence", card.hiddenIntelligence],
    ["The Opening",         card.theOpening],
    ["Recalibrate",         card.reorientation],
    ["Return to Flow",      card.notice],
  ].filter(([,b]) => !!b).map(([t,b]) => sectionBlock(t,b)).join("");

  const attn = card.realignmentPractice ? sectionBlock("Realignment Practice", card.realignmentPractice, true) : "";

  const inner = `
    <div class="fathom-output-card" style="border:none;box-shadow:none;padding:0;margin:0;">
      ${sharedHeader(theme)}
      <main style="padding:16px 20px 20px;">
        ${blocks}
        ${attn}
      </main>
    </div>
    <!-- no extra <hr> here to avoid double line -->
    <div class="disclaimer" style="padding:0 20px 18px; text-align:center;">
      This insight is informational only and not medical advice or a diagnosis. Fathom is a reflective tool and does not treat any condition.
    </div>
  `;

  return emailShell({
    title: theme.header,
    preheader,
    innerHTML: inner,
    viewUrl: reportUrl || "https://alchalign.com/fathom-message"
  });
}

// Plain-text fallback (NO symptom, NO dates)
function buildTextFallback({ product = "fathom", card = {}, reportUrl }) {
  const title = (THEMES[product]?.header) || "Your alchAlign Report";
  const lines = [];
  const push = (arr, t, v) => { if (v) arr.push(`${t}:\n${v}\n`); };

  lines.push(title, ""); // title then blank line
  push(lines, "On the Surface",      card.onTheSurface);
  push(lines, "Consider This",       card.considerThis);
  push(lines, "The Undercurrent",    card.theUndercurrent);
  push(lines, "What’s Emerging",     card.whatsEmerging);
  push(lines, "What's Running Your Life",        card.whatsRunningYourLife);
  push(lines, "The Exchange",        card.theExchange);
  push(lines, "Hidden Intelligence", card.hiddenIntelligence);
  push(lines, "The Opening",         card.theOpening);
  push(lines, "Recalibrate",         card.reorientation);
  push(lines, "Return to Flow",      card.notice);

  if (reportUrl) lines.push(`\nView online: ${reportUrl}`);
  lines.push("— Generated by alchAlign");
  lines.push("This insight is informational only and not medical advice or a diagnosis. Fathom is a reflective tool and does not treat any condition.");
  return lines.join("\n");
}

import juice from "juice";
export default defineComponent({
  async run({ steps, $ }) {
    const RESEND_API_KEY = process.env.RESEND_API_KEY;
    if (!RESEND_API_KEY) throw new Error("RESEND_API_KEY is not set");

    // Expecting previous step to return { email, card }
    const prev = steps.custom_prompt?.$return_value || {};
    const email = prev.email;
    const card  = prev.card || {};
    if (!email) return { skipped: true, reason: "no email provided" };

    const product = steps.trigger?.event?.body?.product || "fathom";

    // Inline styles
    const htmlRaw = buildPremiumEmailHTML({ product, card, reportUrl: "https://alchalign.com/fathom-message" });
    const html = juice(htmlRaw);

    const text = buildTextFallback({ product, card, reportUrl: "https://alchalign.com/fathom-message" });

    const FROM = process.env.RESEND_FROM;
    const SUBJECT = (THEMES[product]?.header) || "Your alchAlign Report";

    async function sendOnce() {
      const res = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          "Authorization": `Bearer ${RESEND_API_KEY}`,
          "Content-Type": "application/json"
        },
        body: JSON.stringify({
          from: FROM,
          to: [email],
          subject: SUBJECT,
          html,
          text
        })
      });
      const body = await res.text();
      return { ok: res.ok, status: res.status, body };
    }

    const attempts = [];
    for (let i = 0; i < 2; i++) {
      const r = await sendOnce();
      attempts.push(r);
      if (r.ok) break;
      await new Promise(r => setTimeout(r, 600));
    }

    const last = attempts[attempts.length - 1];
    if (!last.ok) {
      $.export("email_error", last);
      return { ok: false, attempts };
    }
    return { ok: true, status: last.status, id_or_body: last.body };
  }
});
